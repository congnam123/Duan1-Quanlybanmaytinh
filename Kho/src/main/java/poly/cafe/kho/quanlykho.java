    /**
     * Refresh dữ liệu bảng
     */
    private void refreshTable() {
        try {
            controller.loadData(jTable1);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Lỗi khi làm mới dữ liệu: " + e.getMessage(), 
                "Lỗi", JOptionPane.ERROR_MESSAGE);
        }
    }
    
    /**
     * Hiển thị thống kê kho
     */
    private void showStatistics() {
        try {
            int totalRows = jTable1.getRowCount();
            int selectedRow = jTable1.getSelectedRow();
            
            StringBuilder stats = new StringBuilder();
            stats.append("Thống kê kho:\n");
            stats.append("- Tổng số bản ghi: ").append(totalRows).append("\n");
            
            if (selectedRow >= 0) {
                String maHang = (String) jTable1.getValueAt(selectedRow, 0);
                String tenHang = (String) jTable1.getValueAt(selectedRow, 1);
                stats.append("- Dòng được chọn: ").append(selectedRow + 1).append("\n");
                stats.append("- Mã hàng: ").append(maHang).append("\n");
                stats.append("- Tên hàng: ").append(tenHang).append("\n");
            }
            
            stats.append("- Dữ liệu được cập nhật lần cuối: ").append(new java.util.Date());
            
            JOptionPane.showMessageDialog(this, stats.toString(),
                "Thống kê", JOptionPane.INFORMATION_MESSAGE);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Lỗi khi hiển thị thống kê: " + e.getMessage(), 
                "Lỗi", JOptionPane.ERROR_MESSAGE);
        }
    }
    
    /**
     * Lấy dữ liệu từ bảng và fill vào form với validation
     */
    private void layDuLieuTuBang() {
        int row = jTable1.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn một dòng từ bảng!", 
                "Thông báo", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            // Validation dữ liệu từ bảng
            Object maHangObj = jTable1.getValueAt(row, 0);
            Object tenHangObj = jTable1.getValueAt(row, 1);
            Object soLuongObj = jTable1.getValueAt(row, 2);
            Object giaTienObj = jTable1.getValueAt(row, 3);
            Object trangThaiObj = jTable1.getValueAt(row, 4);
            Object thoiGianObj = jTable1.getValueAt(row, 5);
            
            if (maHangObj == null || tenHangObj == null || soLuongObj == null || 
                giaTienObj == null || trangThaiObj == null) {
                JOptionPane.showMessageDialog(this, "Dữ liệu trong bảng không hợp lệ!", 
                    "Lỗi", JOptionPane.ERROR_MESSAGE);
                return;
            }
            
            // Lấy dữ liệu từ bảng
            String maHang = maHangObj.toString();
            String tenHang = tenHangObj.toString();
            int soLuong = Integer.parseInt(soLuongObj.toString());
            String giaTienStr = giaTienObj.toString().replaceAll("[^0-9]", "");
            double giaTien = Double.parseDouble(giaTienStr);
            String trangThai = trangThaiObj.toString();

            // Validation dữ liệu trước khi fill
            if (maHang.trim().isEmpty() || tenHang.trim().isEmpty() || soLuong <= 0 || giaTien <= 0) {
                JOptionPane.showMessageDialog(this, "Dữ liệu trong bảng không hợp lệ để lấy!", 
                    "Lỗi", JOptionPane.ERROR_MESSAGE);
                return;
            }

            // Fill vào form
            txtmahang.setText(maHang);
            txtnamehang.setText(tenHang);
            txtsoluong.setText(String.valueOf(soLuong));
            txtgiatien.setText(String.valueOf((int)giaTien));
            txttrangthai.setText(trangThai);
            if (thoiGianObj != null) {
                txtthoigian.setText(thoiGianObj.toString());
            }

            // Chuyển sang tab Biểu mẫu
            panl.setSelectedIndex(1);

            JOptionPane.showMessageDialog(this, 
                "Đã lấy dữ liệu từ bảng thành công!\n" +
                "Mã hàng: " + maHang + "\n" +
                "Tên hàng: " + tenHang + "\n" +
                "Số lượng: " + soLuong + "\n" +
                "Giá tiền: " + String.format("%,.0f VNĐ", giaTien) + "\n" +
                "Trạng thái: " + trangThai,
                "Thông báo", JOptionPane.INFORMATION_MESSAGE);

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Lỗi khi chuyển đổi dữ liệu số: " + e.getMessage(), 
                "Lỗi", JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Lỗi khi lấy dữ liệu: " + e.getMessage(), 
                "Lỗi", JOptionPane.ERROR_MESSAGE);
        }
    }

