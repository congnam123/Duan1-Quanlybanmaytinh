    /**
     * Xử lý sự kiện nút Xuất Nhập với validation nâng cao
     */
    private void btxuatnhapActionPerformed(java.awt.event.ActionEvent evt) {
        String maHang = txtmahang.getText().trim();
        String tenHang = txtnamehang.getText().trim();
        String soLuong = txtsoluong.getText().trim();
        String giaTien = txtgiatien.getText().trim();
        String trangThai = txttrangthai.getText().trim();
        
        // Validation trước khi xử lý
        if (!controller.validateForm(maHang, tenHang, soLuong, giaTien, trangThai)) {
            return;
        }
        
        // Gọi controller để xuất nhập kho
        if (controller.xuatNhapKho(maHang, tenHang, soLuong, giaTien, trangThai)) {
        // Clear form và reload data
            controller.clearForm(txtmahang, txtnamehang, txtsoluong, txtgiatien, txttrangthai, txtthoigian);
        refreshTable();
        }
    }
    
    /**
     * Xử lý sự kiện nút Xóa với validation
     */
    private void BtXoaActionPerformed(java.awt.event.ActionEvent evt) {
        // Validation trước khi xóa
        if (!controller.validateDeleteOperation(jTable1)) {
            return;
        }
        
        if (controller.xoaKho(jTable1)) {
            refreshTable();
        }
    }
    
